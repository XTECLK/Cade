// Reads the prompts in prompts/ (a Markdown file each, besides its README.md) into src/mcp-prompts.ts, which Cade's MCP server
// offers in prompts/list and prompts/get. A Worker can't read files, so the folder is read here: adding a
// prompt is adding a file, then `npm run docs` (which `npm run deploy` and `npm run dev` run first).
// test/prompts.test.ts checks src/mcp-prompts.ts is up to date, and that the prompts name only tools and
// fields Cade has.
//
// A prompt's file:
//
//   ---
//   description: One sentence a client shows next to the prompt.
//   arguments:
//     task: What the person gives for it.
//     period?: An argument they may leave out ends in ?.
//   ---
//
//   # The prompt's title
//
//   The instructions, which the agent is given with the arguments after them.
//
// Its name is the file's (task-summary.md is task-summary).
import { readdirSync, readFileSync } from "node:fs";
import type { McpPrompt } from "../src/mcp-prompts.ts";

export const PROMPTS_DIR = new URL("../prompts/", import.meta.url);

export function readPrompts(): McpPrompt[] {
  return readdirSync(PROMPTS_DIR)
    // The README says how to add one; it isn't one.
    .filter((file) => file.endsWith(".md") && file !== "README.md")
    .map((file) => parsePrompt(file.slice(0, -".md".length), readFileSync(new URL(file, PROMPTS_DIR), "utf8")))
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

export function parsePrompt(name: string, source: string): McpPrompt {
  const wrong = (problem: string) => new Error(`prompts/${name}.md: ${problem}`);
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) throw wrong("its name is lowercase words joined by -");
  const parts = /^---\n([\s\S]*?)\n---\n+# (.+)\n+([\s\S]+)$/.exec(source);
  if (!parts) throw wrong("it starts with --- frontmatter ---, then a # title, then the instructions");
  // The three groups always match when the whole does.
  const [, front = "", title = "", body = ""] = parts;
  const description = /^description: (.+)$/m.exec(front)?.[1]?.trim();
  if (!description) throw wrong("its frontmatter has a description");
  const args = /^arguments:\n((?: {2}.+\n?)+)/m.exec(front)?.[1] ?? "";
  const argumentList = args
    .split("\n")
    .filter(Boolean)
    .map((line) => {
      const arg = /^ {2}([a-z_]+)(\??): (.+)$/.exec(line);
      if (!arg) throw wrong(`"${line.trim()}" isn't an argument (name: what it is)`);
      return { name: arg[1]!, description: arg[3]!.trim(), required: !arg[2] };
    });
  return { name, title: title.trim(), description, arguments: argumentList, text: `# ${title.trim()}\n\n${body.trim()}\n` };
}

export function promptsModule(prompts = readPrompts()) {
  return `// Generated by \`npm run docs\` from prompts/*.md (see scripts/prompts.ts): edit those, never this.

// A prompt Cade's MCP server offers: what prompts/list gives, and the text prompts/get gives.
export type McpPrompt = {
  name: string;
  title: string;
  description: string;
  arguments: { name: string; description: string; required: boolean }[];
  text: string;
};

export const PROMPTS: McpPrompt[] = ${JSON.stringify(prompts, null, 2)};
`;
}
